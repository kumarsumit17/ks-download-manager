const lang: "en" | "hi" = typeof navigator !== "undefined" && navigator.language.toLowerCase().startsWith("hi") ? "hi" : "en";

/** The text for `key` in the interface language, with `{name}` placeholders filled in. */
export function t(key: TextKey, params?: Record<string, string | number>): string {
  const text = (lang === "hi" ? hi[key] : en[key]) || en[key];
  return params ? text.replace(/\{(\w+)\}/g, (m, k: string) => (k in params ? String(params[k]) : m)) : text;
}
