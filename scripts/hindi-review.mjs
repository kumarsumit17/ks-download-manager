#!/usr/bin/env node
// Writes docs/hindi-review.md: the glossary, then every interface string (shared
// catalogue, app, extension) as key, English and Hindi, for the owner's review.
// Run `npm run hindi-review` after changing a language file.

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const util = join(root, "node_modules/ks-utility");
const json = (p) => JSON.parse(readFileSync(p, "utf8"));

// Strings whose Hindi is in doubt, with the doubt; marked ⚠ for the owner. The owner's
// final review (2026-11-21) settled every earlier mark, so the list is empty until new
// strings need one.
const UNSURE = {};

const cell = (s) => String(s).replace(/\|/g, "\\|").replace(/\n/g, " ");
const show = (e) => (typeof e === "string" ? e : Object.entries(e).map(([k, v]) => `${k}: ${v}`).join(" · "));

function table(en, hi, unsure) {
  const rows = Object.keys(en).map((k) => {
    const mark = UNSURE[k] ? ` ⚠ ${UNSURE[k]}` : "";
    if (UNSURE[k]) unsure.push(k);
    return `| \`${k}\` | ${cell(show(en[k]))} | ${cell(show(hi[k] ?? "—"))}${cell(mark)} |`;
  });
  return ["| Key | English | Hindi |", "|---|---|---|", ...rows].join("\n");
}

const chrome = (lang) => Object.fromEntries(Object.entries(json(join(root, `extension/_locales/${lang}/messages.json`))).map(([k, v]) => [k, v.message]));
const terms = json(join(util, "lang/hindi-terms.json"));
const unsure = [];
const sections = [
  ["Shared catalogue (ks-utility `lang/common`)", table(json(join(util, "lang/common/en.json")), json(join(util, "lang/common/hi.json")), unsure)],
  ["App (`src/locales`)", table(json(join(root, "src/locales/en.json")), json(join(root, "src/locales/hi.json")), unsure)],
  ["Chrome extension (`extension/_locales`)", table(chrome("en"), chrome("hi"), unsure)],
];

const out = `# Hindi review

Every interface string of KS Download Manager in English and Hindi, for the owner's review. Generated by \`scripts/hindi-review.mjs\` (\`npm run hindi-review\`) from the language files; edit those, not this file. All Hindi text was written by Claude in Stage 5 following ks-utility's \`specs/hindi-style.md\`.

- Strings marked **⚠** are ones I was unsure about (${unsure.length}), with the doubt and an alternative.
- Glossary rows marked **owner review** are terms I added to the style guide; the rest are the owner's.
- Placeholders such as \`{count}\` are filled in by the app; plural forms are listed as \`one: … · other: …\` (Hindi uses \`one\` for 0 and 1).

## Glossary

| English | Hindi | Avoid | Status |
|---|---|---|---|
${terms.map((t) => `| ${cell(t.en)} | ${cell(t.hi)} | ${t.avoid.length ? cell(t.avoid.join(", ")) : "—"} | ${t.review ? "owner review" : "approved"} |`).join("\n")}

${sections.map(([title, body]) => `## ${title}\n\n${body}`).join("\n\n")}
`;
writeFileSync(join(root, "docs/hindi-review.md"), out);
console.log(`docs/hindi-review.md: ${unsure.length} strings marked unsure.`);
